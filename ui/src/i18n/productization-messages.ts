/** Merge only missing leaves so S90 additions never replace established S4 or locale-file copy. */
type MessageTree = Record<string, unknown>;
function mergeMissing(base: MessageTree, additions: MessageTree): MessageTree {
  const merged: MessageTree = { ...base };
  for (const [key, value] of Object.entries(additions)) {
    const current = merged[key];
    if (current === undefined) merged[key] = value;
    else if (isMessageTree(current) && isMessageTree(value)) merged[key] = mergeMissing(current, value);
  }
  return merged;
}
function isMessageTree(value: unknown): value is MessageTree {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

